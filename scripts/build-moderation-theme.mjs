// Derive the standalone dashboard palette from the reader's owning stylesheet.
import {readFileSync,writeFileSync} from 'node:fs';
const source=readFileSync(new URL('../assets/bible-app.css',import.meta.url),'utf8');
const blocks=[...source.matchAll(/(^:root|^\[data-theme="(?:light|dark)"\]|^\[data-theme-preset="[^"]+"\])\s*\{([^}]+)\}/gm)];
const palette='/* Generated by scripts/build-moderation-theme.mjs from bible-app.css. */\n'+blocks.map(([,selector,body])=>`${selector} {\n${body.split('\n').filter(line=>/^\s*--(?:bg|paper|panel|ink|muted|soft|line|teal|teal-dark|accent-ink|accent-hover|gold|gold-soft|success|red-letter|shadow):/.test(line)).join('\n')}\n}`).join('\n');
const output=new URL('../assets/moderation-theme.css',import.meta.url);
if(process.argv.includes('--check')) {
 if(readFileSync(output,'utf8')!==palette) throw new Error('Run node scripts/build-moderation-theme.mjs to sync dashboard palettes.');
 console.log('Dashboard palettes match the reader.');
} else writeFileSync(output,palette);
