import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../assets/bible-app.js', import.meta.url), 'utf8');
const extract = name => source.match(new RegExp(`function ${name}\\([^]*?\\n\\}`))[0];
let saved = null;
const state = { bookmarks: [] };
let syncs = 0;
const context = vm.createContext({ state, localStorage: { getItem: () => saved, setItem: (_, value) => { saved = value; } }, showToast() {}, recordAnnotationDate() {}, scheduleCloudSync() { syncs++; } });
vm.runInContext(['studyToolbarLayout', 'toggleStudyBookmark'].map(extract).join('\n'), context);
const layout = () => JSON.parse(vm.runInContext('JSON.stringify(studyToolbarLayout("verse", ["copy", "note", "bookmark"]))', context));
assert.deepEqual(layout(), [{ id: 'copy', visible: true }, { id: 'note', visible: true }, { id: 'bookmark', visible: true }]);
saved = JSON.stringify([{ id: 'note', visible: false }, { id: 'note' }, { id: 'obsolete' }, { id: 'copy', visible: true }]);
assert.deepEqual(layout(), [{ id: 'note', visible: false }, { id: 'copy', visible: true }, { id: 'bookmark', visible: true }]);
saved = '{broken';
assert.equal(layout().length, 3);
vm.runInContext('toggleStudyBookmark("John 3:16")', context);
assert.deepEqual(state.bookmarks, ['John 3:16']);
assert.equal(saved, '["John 3:16"]');
vm.runInContext('toggleStudyBookmark("John 3:16")', context);
assert.deepEqual(state.bookmarks, []);
assert.equal(syncs, 2);
const selection = extract('selectionBar');
assert.ok(selection.indexOf('id="noteSelection"') < selection.indexOf('id="crossRefSelection"'));
console.log('Toolbar preference recovery, ordering, new controls, and bookmark toggling passed.');
// Newly available optional controls must not change default or saved toolbars.
saved = null;
assert.equal(vm.runInContext('studyToolbarLayout("selection", ["note", "bookmark"], ["bookmark"])[1].visible', context), false);
saved = JSON.stringify([{ id: 'note', visible: true }]);
assert.equal(vm.runInContext('studyToolbarLayout("selection", ["note", "bookmark"], ["bookmark"])[1].visible', context), false);
saved = JSON.stringify([{ id: 'bookmark', visible: true }, { id: 'note', visible: false }]);
assert.equal(vm.runInContext('studyToolbarLayout("selection", ["note", "bookmark"], ["bookmark"])[0].visible', context), true);
console.log('Optional controls preserve defaults and saved visibility.');
// Ignore a retired Highlight control while retaining the other saved choices.
saved = JSON.stringify([{ id: 'data-menu-highlight', visible: true }, { id: 'bookmark', visible: true }, { id: 'note', visible: false }]);
assert.equal(vm.runInContext('JSON.stringify(studyToolbarLayout("selection", ["note", "bookmark"], ["bookmark"]))', context), '[{"id":"bookmark","visible":true},{"id":"note","visible":false}]');
console.log('Retired highlighter action is discarded without resetting other preferences.');
vm.runInContext(extract('toolbarScrollEdges'), context);
const edges = (width, viewport, left) => JSON.parse(vm.runInContext(`JSON.stringify(toolbarScrollEdges(${width}, ${viewport}, ${left}))`, context));
assert.deepEqual(edges(300, 300, 0), { previous: false, next: false });
assert.deepEqual(edges(500, 300, 0), { previous: false, next: true });
assert.deepEqual(edges(500, 300, 100), { previous: true, next: true });
assert.deepEqual(edges(500, 300, 200), { previous: true, next: false });
assert.deepEqual(edges(500, 300, -20), { previous: false, next: true });
assert.deepEqual(edges(500, 300, 220), { previous: true, next: false });
assert.deepEqual(edges(300.5, 300, 0), { previous: false, next: false });
assert.match(source, /data-menu-highlight data-default-hidden="true"/);
assert.match(selection, /id="memorizeSelection" data-default-hidden="true"/);
console.log('Overflow cues cover both ends, middle, fractional layout and overscroll; revised defaults passed.');
// Full-width menus are positioned back inside the viewport for edge verse numbers.
const menu = { style: {}, getBoundingClientRect: () => ({ width: 155, height: 44 }) };
const anchor = { getBoundingClientRect: () => ({ left: 375, width: 12, top: 200, bottom: 216 }) };
const positioning = vm.createContext({ window: { innerWidth: 390 }, menu, anchor });
vm.runInContext(extract('positionVerseActionMenu'), positioning);
vm.runInContext('positionVerseActionMenu(anchor, menu)', positioning);
assert.equal(menu.style.left, '227px');
assert.equal(menu.style.top, '149px');
anchor.getBoundingClientRect = () => ({ left: 2, width: 12, top: 200, bottom: 216 });
vm.runInContext('positionVerseActionMenu(anchor, menu)', positioning);
assert.equal(menu.style.left, '8px');
menu.getBoundingClientRect = () => ({ width: 374, height: 44 });
vm.runInContext('positionVerseActionMenu(anchor, menu)', positioning);
assert.equal(menu.style.left, '8px');
console.log('Verse toolbar positioning keeps left/right edge and viewport-wide menus in bounds.');
