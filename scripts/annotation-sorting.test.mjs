import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../assets/bible-app.js', import.meta.url), 'utf8');
const extract = name => source.match(new RegExp(`function ${name}\\([^]*?\\n\\}`))[0];
const state = { annotationDates: {}, annotationSort: {notes:'newest'}, touchedAnnotationGroupCollections: [], openAnnotationGroups: [] };
const storage = new Map();
const context = vm.createContext({ state, localStorage: {setItem:(k,v)=>storage.set(k,v)}, escapeHtml: s=>String(s), compareReferenceStrings:(a,b)=>a.localeCompare(b), parsePassageReference:()=>({key:'John 3',verses:[16,17]}) });
vm.runInContext(['mergeAnnotationDates','recordAnnotationDate','annotationItemTimestamp','datedAnnotationItemsMarkup','annotationSortMarkup'].map(extract).join('\n'), context);
const run = code => vm.runInContext(code, context);
run(`recordAnnotationDate('notes', 'John 3:16')`);
assert.ok(JSON.parse(storage.get('lw_annotation_dates')).notes['John 3:16']);
state.annotationDates.notes = {'John 3:16':'2026-11-01T12:00:00Z','Genesis 1:1':'2026-11-07T12:00:00Z'};
const render = () => run(`datedAnnotationItemsMarkup([{ref:'John 3:16'}, {ref:'Genesis 1:1'}, {ref:'Unknown'}], item => '[' + item.ref + ']', 'notes')`);
let markup = render();
assert.ok(markup.indexOf('[Genesis') < markup.indexOf('[John'));
assert.ok(markup.indexOf('[Unknown') > markup.indexOf('[John'));
assert.match(markup, /Date unknown/);
state.annotationSort.notes = 'oldest';
markup = render();
assert.ok(markup.indexOf('[John') < markup.indexOf('[Genesis'));
assert.ok(markup.indexOf('[Unknown') > markup.indexOf('[Genesis'));
state.annotationDates.highlights = {'John 3:16':'2026-11-01T12:00:00Z','John 3:17':'2026-11-07T12:00:00Z'};
assert.equal(run(`annotationItemTimestamp('highlights', 'John 3:16-17')`), Date.parse('2026-11-07T12:00:00Z'));
assert.equal(run(`mergeAnnotationDates({notes:{a:'invalid',b:'2026-11-01'}},{notes:{b:'2026-11-07'}}).notes.b`), '2026-11-07T00:00:00.000Z');
state.touchedAnnotationGroupCollections = ['notes'];
state.openAnnotationGroups = [];
assert.doesNotMatch(render(), / open>/);
assert.match(run(`annotationSortMarkup('notes')`), /value="oldest" selected/);
console.log('Annotation sorting: date order, unknown dates, grouped highlights, persistence and merge passed.');
